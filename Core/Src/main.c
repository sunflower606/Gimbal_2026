#include "Delay.h"
#include "gimbal_config.h"
#include "gimbal_task.h"

/* ============================================================================
 * 云台主控板（Gimbal_2026）入口
 *
 * 职责（与《实验室学习项目》需求对应）：
 *   K230 摄像头识别人体 -> 串口把人体框中心像素坐标发来
 *   -> 本板按位置式 PID 调整两路舵机，使人始终处于画面中心。
 *
 * 本板不负责：循迹、电机驱动、模式切换按键、超声测距、双板通信。
 * 这些属于另一块主控（Chassis_20
 *
 * main 只做三件事：初始化一次、按固定周期调用任务、走延时。
 * 所有逻辑都在 application/gimbal_task.c 里。
 * ========================================================================== */

int main(void)
{
    /* 初始化：舵机 PWM、OLED、视觉串口、控制器状态（并把云台摆到中点） */
    GimbalTask_Init();

    for (;;) {
        /* 收帧 -> 控制 -> 输出 PWM（内部按需节流刷屏与回传） */
        GimbalTask_Loop();

        /* 控制周期：必须与 GIMBAL_CONTROL_DT_S 保持一致 */
        Delay_ms(GIMBAL_CONTROL_PERIOD_MS);
    }
}
