#ifndef GIMBAL_CONFIG_H
#define GIMBAL_CONFIG_H

/* ============================================================================
 * 云台控制参数（集中管理）
 *
 * 规范要求：控制参数不允许散落在 .c 文件里，必须集中在 config/。
 * 本文件的每个参数都注明「来源 / 验证方式」，符合《电控 C/C++ 开发规范》
 * 第 9.2 条「PID 参数必须有来源」。
 *
 * 参数来源说明：
 *   下列数值来自 2026-10 在实物二自由度舵机云台上的整定记录，
 *   迁移自 Gimbal_1.0 工程（已验证基本跟随、死区静止、行程限幅）。
 *   迁移时**未改动任何数值**，只重命名并集中到本文件。
 *   详见 docs/技术交付文档.md 的「关键参数与来源」章节。
 * ========================================================================== */

/* ---------------------------------------------------------------- 控制节拍
 * 控制周期 10 ms（100 Hz）。
 * 与 main.c 的 Delay_ms(GIMBAL_CONTROL_PERIOD_MS) 必须一致，
 * 且 PID 微分项按 GIMBAL_CONTROL_DT_S 计算，两者不同步会直接让 D 项失真。
 * ------------------------------------------------------------------------- */
#define GIMBAL_CONTROL_PERIOD_MS            10U
#define GIMBAL_CONTROL_DT_S                 0.01f

/* ------------------------------------------------------------ 任务节流周期
 * 刷 OLED 一次要 3~5 ms（软件 I2C），串口回传一行约 5 ms，
 * 都不能放进 10 ms 的控制节拍里，必须节流。
 * ------------------------------------------------------------------------- */
#define GIMBAL_DISPLAY_PERIOD_MS            100U    /* OLED 刷新周期 */
#define GIMBAL_DEBUG_PERIOD_MS              500U    /* 串口回传周期 */

/* --------------------------------------------------------- 双板链路发送周期
 * 每 30 ms 发一帧给循迹板（与 K230 帧率同步，发更快没有新信息）。
 * 循迹板侧超时 CHASSIS_LINK_TIMEOUT_MS = 500 ms。
 * ------------------------------------------------------------------------- */
#define GIMBAL_LINK_PERIOD_MS               30U

/* 蓝牙命令在链路帧里保持多少帧
 * 手机发一次 "mode2"，云台板解析后把这个命令码连发几帧再清零：
 * 循迹板做的是「边沿检测」（命令码从 0 变成非 0 才动作），多发几帧只是冗余，
 * 不会重复触发。5 帧 = 150 ms，肉眼无感，又能扛住偶发丢帧。
 * 调大：更不容易丢；但命令看起来"粘"在链路上更久（不影响功能）。
 * 调小：1 帧也能用，只是万一那帧被干扰就得重发一次命令。 */
#define GIMBAL_BT_CMD_HOLD_FRAMES           5U

/* 蜂鸣器总开关（上电默认值）
 * 1 = 上电允许发声，0 = 上电静音。
 * 这是"默认值"，不是硬开关：运行中可以用蓝牙 `bz off` / `bz on` 临时改，
 * 但掉电重启后仍以本常量为准 —— 这样彩排静音了，正式比赛重新上电自动恢复。
 * 调大调小：只有 0/1 两个值有意义。改成本值需要重烧云台板才生效。 */
#define GIMBAL_BUZZER_ENABLE                1U

/* ------------------------------------------------------------ 位置式 PID
 * 控制律（单位均为「度」）：
 *     correction = Kp*e + Ki*Σe + Kd*(e - e_last)/dt
 *     angle      = angle + correction × deg_per_unit
 *
 * 其中 e 是「归一化画面偏差」（画面半边 = 100）。
 *
 * 环路增益 K = Kp（deg_per_unit 在「偏差→角度」与「角度→偏差」两处抵消），
 * 闭环极点 P = 1 - K（本装配为负反馈），稳定要求 |P| < 1 即 0 < Kp < 2。
 * 当前 Kp = 0.1 -> P = 0.9，时间常数约 95 ms，偏保守但非常稳。
 *
 * 来源：2026-10-18 现场整定。Kp 从 0.7 降到 0.1 后不再振荡；
 *       Kd 由 0.3 降到 0.01 消除了大幅摆动（Kd 在位置式里被 /dt 放大 100 倍）。
 * ------------------------------------------------------------------------- */
#define GIMBAL_PID_KP                       0.1f
#define GIMBAL_PID_KI                       0.0f     /* 积分关闭：无抗饱和时会顶限位猛弹 */
#define GIMBAL_PID_KD                       0.01f

/* ---------------------------------------------------------- 画面偏差低通
 * 一阶低通：filt += (raw - filt) × alpha
 * K230 约 30 ms 一帧、控制 10 ms 一拍，取 alpha 使时间常数接近一个数据周期：
 *     tau = -dt / ln(1-alpha) = 28 ms  ≈ 一帧 30 ms
 *     α=0.2 时 3 拍只走 48.8%，明显发愣；0.3 时 65.7%，更匹配数据节奏。
 * 来源：2026-10-18 现场整定（先 0.2 后改 0.3）。
 * ------------------------------------------------------------------------- */
/* 输出速率限幅（2026-11-18）：PID 每拍算出的角度增量直接加，最坏能到
 * 150 度/秒，K230 只要跳一次框，云台就甩出去几十度，底盘的偏角随之突跳。
 * 这里把「每拍最多加多少度」限制住：60 度/秒 × 0.01 s = 0.6 度/拍。
 * 追人时 60 度/秒足够（正常人走路横移不到这个角速度的一半）；
 * 想让云台更跟手就调到 90~120，想更稳就调到 30~40。 */
#define GIMBAL_YAW_RATE_MAX_DEG_S            60.0f
#define GIMBAL_PITCH_RATE_MAX_DEG_S          60.0f

#define GIMBAL_LPF_ALPHA                    0.3f

/* ---------------------------------------------------------------- 死区
 * 偏差绝对值小于死区时修正量置 0，云台完全不动，用来压掉检测框抖动。
 * 单位：归一化偏差（100 = 半个画面）。换算像素：
 *     水平 1 单位 = 640/100 = 6.4 px，垂直 1 单位 = 480/100 = 4.8 px
 *     死区 3.0 ≈ 水平 ±19 px、垂直 ±14 px
 * 来源：2026-10-18 仿真实测。检测框抖动 ±12 px 时，
 *       dead_zone >= 2.0 即可让云台 0% 的拍在动；取 3.0 留余量。
 * ------------------------------------------------------------------------- */
#define GIMBAL_DEAD_ZONE                    3.0f

/* -------------------------------------------------------------- 方向符号
 * 画面坐标不反向时，负反馈要求取 -1（已按实机现象确认）。
 * 两个轴独立：哪个轴方向反了只改对应的那一个。
 * 判据：让人站定不动，看 OLED 偏差是否收敛到 0；发散则取反。
 * ------------------------------------------------------------------------- */
#define GIMBAL_SIGN_X                       (-1.0f)
#define GIMBAL_SIGN_Y                       (-1.0f)

/* ------------------------------------------------ 归一化偏差 -> 机械角度
 * 偏差 100（半个画面）折合多少度机械角。
 * 这两个值隐含摄像头视场：水平约 2×15 = 30 度、垂直约 2×12 = 24 度，
 * 比值 1.25 与 1280×960（4:3）的理论比值接近，物理自洽。
 * 来源：2026-10 现场标定（同 Gimbal_1.0）。
 * ------------------------------------------------------------------------- */
#define GIMBAL_DEG_PER_UNIT_X               0.15f
#define GIMBAL_DEG_PER_UNIT_Y               0.12f

/* -------------------------------------------------------------- 行程限幅
 * 舵机电气行程各留 3 度余量：
 *     左右旋转（yaw，270 度舵机）：3 ~ 267
 *     上下俯仰（pitch，180 度舵机）：3 ~ 177
 * 上下界都要限：低于下限同样会让脉宽低于舵机起点而堵转。
 * 来源：2026-10-18 现场确认（舵机标称行程 + 3 度安全余量）。
 * 待实测确认：云台结构真实可动范围可能更窄，装好后应收紧。
 * ------------------------------------------------------------------------- */
#define GIMBAL_YAW_MIN_DEG                  3.0f
#define GIMBAL_YAW_MAX_DEG                  267.0f
#define GIMBAL_PITCH_MIN_DEG                3.0f
#define GIMBAL_PITCH_MAX_DEG                177.0f

/* ------------------------------------------------------------ 上电初始角度
 * 两个中点（脉宽都是 1500 us）：
 *     左右旋转 0~270 -> 中点 135
 *     上下俯仰 0~180 -> 中点  90
 * ------------------------------------------------------------------------- */
#define GIMBAL_YAW_HOME_DEG                 135.0f
#define GIMBAL_PITCH_HOME_DEG               90.0f

/* --------------------------------------------------- 底盘链路用的 yaw 零点
 * 「云台 yaw 为多少度时，摄像头正好正对车头前进方向」。
 * 发给循迹板的偏角 = (yaw - 本值) × 10，所以本值错了，底盘就会以为人一直在偏，
 * 表现为车绕着人原地打转、走不了直线。
 *
 * 摄像头如果装歪了（或舵盘齿没对正），这里要跟着改，**以实测为准**，
 * 不要靠"偏左还是偏右"去猜方向。
 *
 * ⚠️ 这个零点**不改变**云台上电位置（那还是 GIMBAL_YAW_HOME_DEG）和
 *    3~267 度的行程限幅，只影响「怎么把 yaw 折算成底盘用的偏角」。
 *
 * 标定方法（唯一可靠的做法，直接量）：
 *   1) 车摆正，人站车头正前方 1.5 m 处不动；
 *   2) 等云台把人放到画面中心（不再动），读底盘串口的 dev=（单位 0.1 度）；
 *   3) 新值 = 当前值 + dev/10。
 *      例：当前 135、dev=+300 => 135 + 30 = 165；dev=-300 => 135 - 30 = 105。
 *   4) 改完重烧云台板，再测 dev 应接近 0（±20 以内即可）。
 * ------------------------------------------------------------------------- */
#define GIMBAL_CHASSIS_ZERO_DEG             109.1f   /* 二次标定 2026-11-16：人站正前方 dev=+68 => 102.3 + 6.8 */

/* ------------------------------------------------------------ 目标丢失判定
 * 超过该时间没有收到「检测到人」的帧，就认为目标丢失，云台保持角度不动。
 * K230 未检测到人时每 200 ms 补发一帧丢失帧，所以 300 ms 足够覆盖两种情况：
 *     1) K230 正常但没有目标（收到 -1/-1 帧，立即可判）
 *     2) K230 断线或死机（300 ms 内没有任何帧）
 * ------------------------------------------------------------------------- */
#define GIMBAL_LOSE_TIMEOUT_MS              300U

/* --------------------------------------------------------- 限位反向扫视
 * 用途（2026-11-19 新增，主要给模式 1 循迹用）：
 *   人跑到了云台"转到极限也看不到"的方位时，云台会顶在 3 度或 267 度上，
 *   如果一直顶住不动，就永远等不到人重新出现。这里让云台
 *   「顶到限位就往反方向扫」，扫到另一端再折回来，直到重新看到人为止。
 *
 * 触发条件（满足任一即触发，2026-11-20 改为双条件）：
 *   A) 快速触发：目标丢失 + yaw 贴在端点 ±GIMBAL_SWEEP_EDGE_DEG 内
 *      连续 GIMBAL_SWEEP_CONFIRM_MS（对应"真被车身推到限位"的场景）
 *   B) 兜底触发：目标丢失累计 GIMBAL_SWEEP_TRIGGER_MS（从最后一帧算起）
 *      实测云台一丢人就"保持不动"，通常停在离端点几十度处（实测 239 度），
 *      条件 A 永远不成立 -> 扫视一次都不触发，所以必须有这条兜底。
 *
 * 结束条件（任一）：
 *   1) 重新检测到人 -> 立即恢复正常跟踪（下一拍就按 PID 走）
 *   2) 扫够 GIMBAL_SWEEP_PASSES 个单程仍没看到人 -> 回上电中点并放弃
 *
 * 扫视速度：45 度/秒。全行程 264 度 ÷ 45 = 5.9 s 一个单程。
 *   为什么不是更快：K230 30 ms 一帧，45 度/秒 时每帧只转 1.35 度，
 *   远小于 65 度视场，绝不会"跳过去"漏掉人；再快就到 90 度/秒（2.7 度/帧，
 *   也够用）但画面拖影更明显，检测置信度会掉。
 *   为什么这么慢还能用：扫视只在"人已经彻底看不到"时才启动，属于兜底动作，
 *   不急；宁慢勿漏。
 * ------------------------------------------------------------------------- */
#define GIMBAL_SWEEP_SPEED_DEG_S            60.0f   /* 扫视角速度，单位 度/秒 */
#define GIMBAL_SWEEP_CONFIRM_MS             300U    /* 贴限位持续多久才认定"撞死" */
#define GIMBAL_SWEEP_TRIGGER_MS             800U    /* 丢人多久后无条件开始扫（从最后一帧算起） */
#define GIMBAL_SWEEP_EDGE_DEG               5.0f    /* 距端点多少度以内算"贴边"（2026-11-19 由 1.5 放宽到 5，舵机逼近端点时会先减速+回弹，1.5 太严常常触发不了） */
#define GIMBAL_SWEEP_PASSES                 6U      /* 单程数：6 个单程 = 3 个来回 */

/* ------------------------------------------------- 上电静默（2026-11-20）
 * 问题：K230 从上电到输出第一帧需要 5~15 s（Linux 启动 + 加载 kmodel）。
 * 这段时间云台收不到任何帧 = 一直"判丢"，800 ms 后就开始扫视 ——
 * 人还没开机就被云台自己转了一大圈，还会顶限位。
 * 对策：两道闸门，任一未满足都不许扫视，云台原地不动。
 *   1) GIMBAL_BOOT_GRACE_MS：上电后这么久之内不扫（兜底，防"摄像头永远不来"）
 *   2) GIMBAL_SWEEP_NEED_TARGET：必须先成功跟踪到人一次，才允许扫视
 *      （"从没见过人"就不存在"找人"，避免空场景乱扫）
 * ------------------------------------------------------------------------- */
#define GIMBAL_BOOT_GRACE_MS                8000U   /* 上电后禁止扫视的时间窗，ms */
#define GIMBAL_SWEEP_NEED_TARGET            1U      /* 1 = 必须曾跟踪到人才允许扫视 */

#endif /* GIMBAL_CONFIG_H */
