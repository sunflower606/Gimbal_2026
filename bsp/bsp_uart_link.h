#ifndef BSP_UART_LINK_H
#define BSP_UART_LINK_H

/* ============================================================================
 * BSP：双板链路串口（USART1，只发不收）
 *
 * 用途：把「云台 yaw 偏角」发给循迹板，供模式 2（纯人体跟随）转向使用。
 *
 * 为什么只发：云台板不需要循迹板的任何数据 —— 模式由循迹板自己决定，
 * 云台板无论哪个模式都继续跟踪人。只发不收可以省掉中断与环形缓冲。
 *
 * 层次约定：本文件是云台板上唯一允许操作 USART1 的地方。
 * ========================================================================== */

#include <stdint.h>

/* 初始化 USART1：PA9 = TX，115200-8-N-1，仅发送模式 */
void BSP_Link_Init(void);

/**
 * @brief 阻塞发送一段字节。
 * @param data 数据指针；为 NULL 或 len 为 0 时直接返回。
 * @param len  字节数。
 *
 * @note 阻塞式（每字节等 TXE）。一帧 13 字节 @115200 约 1.1 ms，
 *       调用方必须节流，不能放进 10 ms 控制环的每一拍。
 */
void BSP_Link_SendBuffer(const uint8_t *data, uint16_t len);

#endif /* BSP_UART_LINK_H */
